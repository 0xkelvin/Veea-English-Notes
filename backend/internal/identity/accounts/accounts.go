// Package accounts is the database side of the identity module: the only code that writes the
// users table (TRD 2.2). It is a separate package so internal/identity itself stays free of
// database code; hashing and policy checks happen there, before any transaction.
//
// Every function takes the caller's connection or transaction. Callers follow the lock order of
// TRD 7.1: an insert here is lock level L3 for a new account.
package accounts

import (
	"context"
	"errors"
	"fmt"
	"time"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"

	"github.com/0xkelvin/Veea-English-Notes/backend/internal/identity"
	"github.com/0xkelvin/Veea-English-Notes/backend/internal/platform/db/sqlc"
)

// Status values (TRD 3.1).
const StatusActive = "active"

// Find reads the account for a normalized email without a lock (TRD 7.2 step 3). ok is false
// when there is none.
func Find(ctx context.Context, db sqlc.DBTX, e identity.Email) (u sqlc.User, ok bool, err error) {
	u, err = sqlc.New(db).GetUserByEmailNormalized(ctx, e.Normalized)
	if errors.Is(err, pgx.ErrNoRows) {
		return sqlc.User{}, false, nil
	}
	if err != nil {
		return sqlc.User{}, false, fmt.Errorf("accounts: find: %w", err)
	}
	return u, true, nil
}

// Get reads the account by id without a lock (GET /v1/me, token responses). ok is false when
// there is none.
func Get(ctx context.Context, db sqlc.DBTX, id uuid.UUID) (u sqlc.User, ok bool, err error) {
	u, err = sqlc.New(db).GetUserByID(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return sqlc.User{}, false, nil
	}
	if err != nil {
		return sqlc.User{}, false, fmt.Errorf("accounts: get: %w", err)
	}
	return u, true, nil
}

// LockForNoKeyUpdate locks the account at level L3 (TRD 7.1), the only explicit lock mode ever
// taken on users. ok is false when the account no longer exists.
func LockForNoKeyUpdate(ctx context.Context, tx pgx.Tx, id uuid.UUID) (u sqlc.User, ok bool, err error) {
	u, err = sqlc.New(tx).LockUserForNoKeyUpdate(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return sqlc.User{}, false, nil
	}
	if err != nil {
		return sqlc.User{}, false, fmt.Errorf("accounts: lock: %w", err)
	}
	return u, true, nil
}

// ReplacePasswordHash stores a rehash of the same password (new parameters) on a row the
// transaction holds at L3. It is a compare-and-set on the old hash, so it never overwrites a
// concurrent change, and it does not touch password_changed_at (TRD 9.2). It reports whether
// the row was updated.
func ReplacePasswordHash(ctx context.Context, tx pgx.Tx, id uuid.UUID, oldHash, newHash string) (bool, error) {
	n, err := sqlc.New(tx).RehashUserPassword(ctx, sqlc.RehashUserPasswordParams{ID: id, OldHash: &oldHash, NewHash: &newHash})
	if err != nil {
		return false, fmt.Errorf("accounts: rehash: %w", err)
	}
	return n == 1, nil
}

// SetPassword writes a new password hash and password_changed_at = now() on a row the
// transaction already holds at L3 (set, change, reset; TRD 7.5).
func SetPassword(ctx context.Context, tx pgx.Tx, id uuid.UUID, hash string) error {
	n, err := sqlc.New(tx).SetUserPassword(ctx, sqlc.SetUserPasswordParams{ID: id, PasswordHash: &hash})
	if err != nil {
		return fmt.Errorf("accounts: set password: %w", err)
	}
	if n != 1 {
		return errors.New("accounts: set password: locked account not updated")
	}
	return nil
}

// NewVerified is an account created by a verified signup (TRD 3.1, 7.3).
type NewVerified struct {
	ID    uuid.UUID // UUIDv7, generated by the caller before the transaction
	Email identity.Email
	// PasswordHash is the argon2id PHC string of a password signup, or empty for OTP signup.
	PasswordHash string
	// VerifiedAt is the database time of the verification (the transaction's now()).
	VerifiedAt time.Time
}

// CreateVerified inserts the account with email_verified_at set, or does nothing if the email
// already has an account. created is false in that case and the existing row is never read or
// changed, so a duplicate signup cannot alter an existing account's credentials (AC-27).
//
// A concurrent signup for the same email waits on the unique index until the other transaction
// ends (TRD 7.3).
func CreateVerified(ctx context.Context, tx pgx.Tx, a NewVerified) (u sqlc.User, created bool, err error) {
	if a.ID == uuid.Nil || a.Email.Normalized == "" || a.VerifiedAt.IsZero() {
		return sqlc.User{}, false, errors.New("accounts: id, email and verification time are required")
	}
	p := sqlc.InsertUserIfAbsentParams{
		ID: a.ID, Email: a.Email.Display, EmailNormalized: a.Email.Normalized, EmailVerifiedAt: &a.VerifiedAt,
	}
	if a.PasswordHash != "" {
		// A password signup sets the first password at creation (TRD 5.2: null until set).
		p.PasswordHash, p.PasswordChangedAt = &a.PasswordHash, &a.VerifiedAt
	}
	u, err = sqlc.New(tx).InsertUserIfAbsent(ctx, p)
	if errors.Is(err, pgx.ErrNoRows) {
		return sqlc.User{}, false, nil
	}
	if err != nil {
		return sqlc.User{}, false, fmt.Errorf("accounts: create: %w", err)
	}
	return u, true, nil
}

// InGoodStanding reports whether u may sign in (TRD 3.3): active and verified.
func InGoodStanding(u sqlc.User) bool {
	return u.Status == StatusActive && u.EmailVerifiedAt != nil
}

// LockForKeyShare holds the account at L3 in its weakest mode (TRD 05 §14) for learning writes:
// the row cannot be erased meanwhile, but no other L3 mode waits on it. ok is false when the
// account no longer exists.
func LockForKeyShare(ctx context.Context, tx pgx.Tx, id uuid.UUID) (u sqlc.User, ok bool, err error) {
	u, err = sqlc.New(tx).LockUserForKeyShare(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return sqlc.User{}, false, nil
	}
	if err != nil {
		return sqlc.User{}, false, fmt.Errorf("accounts: lock key share: %w", err)
	}
	return u, true, nil
}
